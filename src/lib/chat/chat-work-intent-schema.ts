/** JSON schema pro OpenAI Responses (strict). */

const detectedItemSchema = {
  type: "object",
  additionalProperties: false,
  properties: {
    itemId: { type: "string" },
    type: {
      type: "string",
      enum: ["reservation", "job", "task", "meeting", "note", "unclear"],
    },
    title: { type: ["string", "null"] },
    customerName: { type: ["string", "null"] },
    companyName: { type: ["string", "null"] },
    phone: { type: ["string", "null"] },
    email: { type: ["string", "null"] },
    address: { type: ["string", "null"] },
    description: { type: ["string", "null"] },
    startDate: { type: ["string", "null"] },
    endDate: { type: ["string", "null"] },
    scheduledTime: { type: ["string", "null"] },
    sourceText: { type: ["string", "null"] },
    yearNeedsConfirmation: { type: "boolean" },
    confidence: { type: "number" },
    assignedEmployeeHint: { type: ["string", "null"] },
  },
  required: [
    "itemId",
    "type",
    "title",
    "customerName",
    "companyName",
    "phone",
    "email",
    "address",
    "description",
    "startDate",
    "endDate",
    "scheduledTime",
    "sourceText",
    "yearNeedsConfirmation",
    "confidence",
    "assignedEmployeeHint",
  ],
} as const;

